"""Compose the final reaction video with split-screen layout and overlays."""
import logging
from pathlib import Path
from datetime import datetime

import numpy as np
from PIL import Image, ImageDraw, ImageFont
from moviepy import (
    VideoFileClip,
    ImageClip,
    CompositeVideoClip,
    TextClip,
    ColorClip,
    concatenate_videoclips,
)
from moviepy.video.fx import Resize

import sys
sys.path.insert(0, str(Path(__file__).parent.parent))
import config
from src.video_fetcher import VideoInfo
from src.commentary_generator import CommentaryBeat

logger = logging.getLogger(__name__)


class ReactionComposer:
    """Builds a reaction video: split-screen game footage + reaction panel."""

    W = config.OUTPUT_WIDTH
    H = config.OUTPUT_HEIGHT
    FPS = config.FPS

    HEADER_H = config.HEADER_HEIGHT
    FOOTER_H = config.FOOTER_HEIGHT
    CONTENT_H = H - HEADER_H - FOOTER_H

    GAME_W = int(W * config.GAME_VIDEO_RATIO)
    REACT_W = W - GAME_W

    def __init__(self):
        self._load_fonts()

    def _load_fonts(self):
        """Load fonts; fall back to PIL default if custom fonts unavailable."""
        try:
            font_path = str(config.FONTS_DIR / "Roboto-Bold.ttf")
            self.font_title = ImageFont.truetype(font_path, 28)
            self.font_body = ImageFont.truetype(font_path, 22)
            self.font_small = ImageFont.truetype(font_path, 16)
        except (IOError, OSError):
            self.font_title = ImageFont.load_default(size=28)
            self.font_body = ImageFont.load_default(size=22)
            self.font_small = ImageFont.load_default(size=16)

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def compose(
        self,
        video: VideoInfo,
        clip_path: Path,
        beats: list[CommentaryBeat],
        output_dir: Path = config.OUTPUT_DIR,
    ) -> Path:
        """Compose and export the reaction video.

        Args:
            video: Metadata for the source CC-licensed video
            clip_path: Path to the downloaded video clip
            beats: Commentary beats generated by CommentaryGenerator
            output_dir: Directory to save the output

        Returns:
            Path to the exported reaction video
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        out_path = output_dir / config.OUTPUT_FILENAME_TEMPLATE.format(
            video_id=video.video_id, timestamp=timestamp
        )

        logger.info("Composing reaction video for '%s'", video.title)

        game_clip = VideoFileClip(str(clip_path))
        duration = min(game_clip.duration, config.CLIP_DURATION)
        game_clip = game_clip.subclipped(0, duration)

        layers = [
            self._build_background(duration),
            self._build_header(video, duration),
            self._build_game_panel(game_clip),
            self._build_reaction_panel(video, duration),
            self._build_footer(duration),
            self._build_attribution(video, duration),
        ]
        layers += self._build_commentary_overlays(beats, duration)

        final = CompositeVideoClip(layers, size=(self.W, self.H)).with_fps(self.FPS)
        final = final.with_audio(game_clip.audio)  # keep original audio

        logger.info("Exporting to %s", out_path)
        final.write_videofile(
            str(out_path),
            codec=config.OUTPUT_CODEC,
            audio_codec=config.OUTPUT_AUDIO_CODEC,
            bitrate=config.OUTPUT_BITRATE,
            logger=None,
        )
        game_clip.close()
        final.close()

        logger.info("Done! Saved to %s", out_path)
        return out_path

    # ------------------------------------------------------------------
    # Layer builders
    # ------------------------------------------------------------------

    def _build_background(self, duration: float) -> ColorClip:
        return ColorClip(
            size=(self.W, self.H),
            color=config.COLOR_BG,
        ).with_duration(duration)

    def _build_header(self, video: VideoInfo, duration: float) -> ImageClip:
        img = Image.new("RGB", (self.W, self.HEADER_H), config.COLOR_HEADER)
        draw = ImageDraw.Draw(img)

        title = f"🎮 REACTING TO: {video.title[:70]}"
        draw.text((20, 15), title, fill=config.COLOR_TEXT_PRIMARY, font=self.font_title)

        right_text = f"{video.view_count:,} views • {video.channel_title}"
        bbox = draw.textbbox((0, 0), right_text, font=self.font_small)
        text_w = bbox[2] - bbox[0]
        draw.text(
            (self.W - text_w - 20, 22),
            right_text,
            fill=config.COLOR_TEXT_PRIMARY,
            font=self.font_small,
        )

        return (
            ImageClip(np.array(img))
            .with_duration(duration)
            .with_position((0, 0))
        )

    def _build_game_panel(self, game_clip: VideoFileClip) -> VideoFileClip:
        """Resize game footage to fit the left panel."""
        target_h = self.CONTENT_H
        target_w = self.GAME_W

        resized = game_clip.resized((target_w, target_h))
        return resized.with_position((0, self.HEADER_H))

    def _build_reaction_panel(self, video: VideoInfo, duration: float) -> ImageClip:
        """Static reaction panel with channel info and emoji grid."""
        img = Image.new("RGB", (self.REACT_W, self.CONTENT_H), config.COLOR_REACTION_BG)
        draw = ImageDraw.Draw(img)

        # Panel border
        draw.rectangle([0, 0, self.REACT_W - 1, self.CONTENT_H - 1], outline=config.COLOR_ACCENT, width=2)

        # Webcam placeholder
        cam_h = int(self.CONTENT_H * 0.45)
        cam_rect = [10, 10, self.REACT_W - 10, cam_h]
        draw.rectangle(cam_rect, fill=(20, 20, 30), outline=config.COLOR_ACCENT, width=1)
        draw.text(
            (self.REACT_W // 2 - 30, cam_h // 2 - 20),
            "📹 LIVE",
            fill=config.COLOR_ACCENT,
            font=self.font_title,
        )
        draw.text(
            (self.REACT_W // 2 - 50, cam_h // 2 + 10),
            "REACTION CAM",
            fill=config.COLOR_TEXT_SECONDARY,
            font=self.font_small,
        )

        # Reaction emoji grid
        y_start = cam_h + 20
        emojis = config.REACTION_EMOJIS[:6]
        cols = 3
        cell_w = (self.REACT_W - 20) // cols
        for i, (emoji, label) in enumerate(emojis):
            row, col = divmod(i, cols)
            x = 10 + col * cell_w + cell_w // 2 - 15
            y = y_start + row * 50
            draw.text((x, y), emoji, fill=config.COLOR_TEXT_PRIMARY, font=self.font_body)
            draw.text((x - 5, y + 22), label, fill=config.COLOR_TEXT_SECONDARY, font=self.font_small)

        # "AUTO REACTION" label
        draw.text(
            (10, self.CONTENT_H - 35),
            "⚡ AUTO REACTION CHANNEL",
            fill=config.COLOR_ACCENT,
            font=self.font_small,
        )

        return (
            ImageClip(np.array(img))
            .with_duration(duration)
            .with_position((self.GAME_W, self.HEADER_H))
        )

    def _build_footer(self, duration: float) -> ImageClip:
        """Animated progress bar footer."""
        # Build a static footer image (progress bar is added as overlay separately)
        img = Image.new("RGB", (self.W, self.FOOTER_H), (10, 10, 15))
        draw = ImageDraw.Draw(img)
        draw.rectangle([0, 0, self.W - 1, self.FOOTER_H - 1], outline=(40, 40, 50), width=1)

        # Track area
        draw.rectangle([60, 15, self.W - 120, 25], fill=(50, 50, 60), outline=(80, 80, 90))

        # Time labels
        draw.text((10, 15), "▶  0:00", fill=config.COLOR_TEXT_PRIMARY, font=self.font_small)
        total = f"-{config.CLIP_DURATION // 60}:{config.CLIP_DURATION % 60:02d}"
        draw.text((self.W - 110, 15), total, fill=config.COLOR_TEXT_SECONDARY, font=self.font_small)

        # Disclaimer
        draw.text(
            (10, 32),
            "CC BY Licensed Content — See description for attribution",
            fill=(120, 120, 130),
            font=self.font_small,
        )

        return (
            ImageClip(np.array(img))
            .with_duration(duration)
            .with_position((0, self.HEADER_H + self.CONTENT_H))
        )

    def _build_attribution(self, video: VideoInfo, duration: float) -> ImageClip:
        """Small attribution overlay in top-left of game panel."""
        text = f"CC BY: {video.channel_title}"
        w, h = 300, 28
        img = Image.new("RGBA", (w, h), (0, 0, 0, 160))
        draw = ImageDraw.Draw(img)
        draw.text((6, 5), text, fill=(200, 200, 200, 255), font=self.font_small)
        return (
            ImageClip(np.array(img))
            .with_duration(duration)
            .with_position((10, self.HEADER_H + 10))
        )

    def _build_commentary_overlays(
        self, beats: list[CommentaryBeat], duration: float
    ) -> list[ImageClip]:
        """Create timed commentary bubble overlays."""
        overlays = []
        display_dur = 3.0  # each bubble shows for 3 seconds

        for beat in beats:
            if beat.timestamp >= duration:
                continue

            img = self._render_commentary_bubble(beat)
            clip = (
                ImageClip(np.array(img))
                .with_start(beat.timestamp)
                .with_duration(min(display_dur, duration - beat.timestamp))
                .with_position((20, self.HEADER_H + self.CONTENT_H - 120))
            )
            overlays.append(clip)

        return overlays

    def _render_commentary_bubble(
        self, beat: CommentaryBeat
    ) -> Image.Image:
        """Render a commentary speech bubble as a PIL Image."""
        padding = 12
        base_w = min(500, self.GAME_W - 40)
        h = 60

        img = Image.new("RGBA", (base_w, h), (0, 0, 0, 0))
        draw = ImageDraw.Draw(img)

        # Bubble background
        bubble_color = (
            int(255 * beat.intensity),
            int(80 * (1 - beat.intensity)),
            int(80 * (1 - beat.intensity)),
            210,
        )
        draw.rounded_rectangle([0, 0, base_w - 1, h - 1], radius=12, fill=bubble_color)

        # Emoji
        draw.text((padding, 12), beat.emoji, font=self.font_body, fill=(255, 255, 255, 255))

        # Commentary text
        draw.text(
            (padding + 35, 15),
            beat.text,
            font=self.font_body,
            fill=(255, 255, 255, 255),
        )

        return img
